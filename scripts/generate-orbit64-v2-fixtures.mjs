// Generates test/fixtures/orbit64-v2-vectors.mjs from a flix-orbit64 checkout.
//
//     node scripts/generate-orbit64-v2-fixtures.mjs [path-to-flix-orbit64]
//
// The default checkout path is ../flix-orbit64. Nothing is computed here: rows
// are copied verbatim from test/TestV2VectorData.flix (V2 reference vectors)
// and test/TestVectors.flix (V1 state tokens with their corner coordinates).
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const flix = resolve(process.argv[2] ?? join(root, "..", "flix-orbit64"));
const read = (path) => readFileSync(join(flix, path), "utf8");

const rows = [...read("test/TestV2VectorData.flix").matchAll(/^\s*\((\d+), "([^"]*)", "([^"]*)"\),?$/gm)]
  .map(([, id, text, token]) => [Number(id), text, token]);
if (rows.length !== 195) throw new Error(`expected 195 reference rows, found ${rows.length}`);

// V1 token widths, and the V2 color framed entry that reads them (FORMAT-V2.md).
const widths = {2: 5, 3: 12, 4: 27, 6: 66, 7: 90};
const entries = {2: 1, 3: 3, 4: 7, 6: 15, 7: 19};
const numbers = (text) => text.split(",").map((part) => Number(part.trim()));
const v1 = [];
const blocks = read("test/TestVectors.flix").split(/^@Test$/m);
for (const block of blocks) {
  const name = /def test(\d+)x\d+(\w+)Encodes\(\)/.exec(block);
  if (!name || !(Number(name[1]) in widths)) continue;
  const n = Number(name[1]);
  const corner = /CornerCoord\(Vector#\{([^}]*)\}, Vector#\{([^}]*)\}\)/.exec(block);
  const literal = /Ok\("([^"]+)"\)/.exec(block);
  const token = literal ? literal[1] : "A".repeat(widths[n]);
  if (!corner || token.length !== widths[n]) throw new Error(`cannot read V1 vector ${name[0]}`);
  v1.push([n, entries[n], token, numbers(corner[1]), numbers(corner[2])]);
}

const lines = (items, format) => items.map((item) => `  ${format(item)},`).join("\n");
const text = `// Generated by scripts/generate-orbit64-v2-fixtures.mjs. Do not edit.
//
// Source: flix-orbit64 (the Flix reference implementation of FORMAT-V2.md).
//   referenceVectors   test/TestV2VectorData.flix, itself generated by that
//                      repository's independent Julia encoder tools/format-v2/vectors.jl.
//                      Rows are [entry id, state text, token]. State text is
//                      \`key=v,v,...;\` with keys cp ct mp mf w1.. z1.. fr fm.
//   v1StateVectors     test/TestVectors.flix, V1 state tokens produced by an
//                      independent geometric reference model. Rows are
//                      [n, V2 entry id that reads the token, V1 token,
//                      corner pieces, corner twists].

export const referenceVectors = [
${lines(rows, (row) => JSON.stringify(row))}
];

export const v1StateVectors = [
${lines(v1, (row) => JSON.stringify(row))}
];
`;
writeFileSync(join(root, "test/fixtures/orbit64-v2-vectors.mjs"), text);
console.log(`wrote ${rows.length} reference rows and ${v1.length} V1 rows`);
